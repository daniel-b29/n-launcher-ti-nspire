static uint16_t *g_fb = NULL;

static void fill_rect(int x, int y, int w, int h, uint16_t c) {
    if (!g_fb) return;
    int x0 = x < 0 ? 0 : x, y0 = y < 0 ? 0 : y;
    int x1 = x + w > KP_W ? KP_W : x + w;
    int y1 = y + h > KP_H ? KP_H : y + h;
    for (int py = y0; py < y1; py++) {
        uint16_t *r = g_fb + py * KP_W;
        for (int px = x0; px < x1; px++) r[px] = c;
    }
}

static void draw_box(int x, int y, int w, int h, uint16_t bg, uint16_t border) {
    fill_rect(x, y, w, h, border);
    if (w > 2 && h > 2) fill_rect(x + 1, y + 1, w - 2, h - 2, bg);
}

static void draw_text(int x, int y, const char *s, uint16_t c) {
    if (!g_fb || !s) return;
    int cx = x;
    while (*s) {
        unsigned char ch = (unsigned char)(*s++);
        if (ch < 32U || ch > 126U) ch = '?';
        const uint8_t *g = k_font5x7[ch - 32U];
        for (int col = 0; col < 5; col++) {
            int px = cx + col;
            if (px < 0 || px >= KP_W) continue;
            uint8_t bits = g[col];
            for (int row = 0; row < 7; row++) {
                int py = y + row;
                if (py >= 0 && py < KP_H && (bits & (1U << row))) g_fb[py * KP_W + px] = c;
            }
        }
        cx += 6;
        if (cx >= KP_W) break;
    }
}

static void safe_delay_ms(unsigned ms) {
    if (is_classic) { msleep(ms); return; }
    volatile unsigned *t2_load = (volatile unsigned *)0x900D0020;
    volatile unsigned *t2_val  = (volatile unsigned *)0x900D0024;
    volatile unsigned *t2_ctrl = (volatile unsigned *)0x900D0028;
    unsigned oc = *t2_ctrl, ol = *t2_load;
    *t2_ctrl = 0; *t2_load = 0xFFFFFFFFU; *t2_ctrl = 0x82U;
    unsigned st = *t2_val, tgt = ms * 33U;
    while ((unsigned)(st - *t2_val) < tgt) { __asm__ volatile("nop"); }
    *t2_ctrl = 0; *t2_load = ol; *t2_ctrl = oc;
}

int main(void) {
    g_fb = (uint16_t *)calloc(KP_W * KP_H, sizeof(uint16_t));
    if (!g_fb) return 1;
    if (!lcd_init(SCR_320x240_565)) { free(g_fb); return 1; }

    unsigned last_off = 0U;
    uint16_t last_val = 0U;
    bool     last_sp = false;
    unsigned exit_hold = 0U;

    while (1) {
        bool sp   = is_touchpad && isKeyPressed(KEY_NSPIRE_SCRATCHPAD);
        bool ctrl = isKeyPressed(KEY_NSPIRE_CTRL);
        bool skey = isKeyPressed(KEY_NSPIRE_S);
        bool doc  = isKeyPressed(KEY_NSPIRE_DOC);
        bool menu = isKeyPressed(KEY_NSPIRE_MENU);
        bool esc  = isKeyPressed(KEY_NSPIRE_ESC);
        bool onk  = on_key_pressed();

        uint16_t rows[8];
        for (int i = 0; i < 8; i++) {
            unsigned off = 0x10U + (unsigned)(i * 2);
            uint16_t raw = *(const volatile uint16_t *)(uintptr_t)(0x900E0000U + off);
            uint16_t v = is_classic ? (uint16_t)(~raw & 0x07FFU) : (uint16_t)(raw & 0x07FFU);
            rows[i] = v;
            if (v != 0U) {
                last_off = off;
                last_val = v;
            }
        }
        if (sp) last_sp = true;

        if (esc || onk) {
            exit_hold++;
            if (exit_hold >= 25U) break;
        } else {
            exit_hold = 0U;
        }

        fill_rect(0, 0, KP_W, KP_H, COL_BG);
        fill_rect(0, 0, KP_W, 24, COL_CARD);
        fill_rect(0, 24, KP_W, 1, COL_BORDER);
        draw_text(8, 8, "KEY PROBE CX II-T  -  MATRICE CLAVIER", COL_ACCENT);

        draw_box(8, 32, 304, 86, COL_CARD, COL_BORDER);
        draw_text(14, 38, "Registres actifs 0x900E0010..1E (bit=1 appui):", COL_TEXT);
        char line[60];
        snprintf(line, sizeof(line), "0x10:%04X  0x12:%04X  0x14:%04X  0x16:%04X",
                 rows[0], rows[1], rows[2], rows[3]);
        draw_text(14, 54, line, COL_MUTED);
        snprintf(line, sizeof(line), "0x18:%04X  0x1A:%04X  0x1C:%04X  0x1E:%04X",
                 rows[4], rows[5], rows[6], rows[7]);
        draw_text(14, 68, line, COL_MUTED);
        snprintf(line, sizeof(line), "Dernier code lu : off=0x%02X  val=0x%04X",
                 last_off, last_val);
        draw_text(14, 88, line, last_off ? COL_OK : COL_WARN);
        snprintf(line, sizeof(line), "is_touchpad=%d  is_cx2=%d  is_classic=%d",
                 is_touchpad ? 1 : 0, is_cx2 ? 1 : 0, is_classic ? 1 : 0);
        draw_text(14, 102, line, COL_MUTED);

        draw_box(8, 126, 304, 72, COL_CARD, COL_BORDER);
        draw_text(14, 134, "TESTS NDLESS isKeyPressed() :", COL_ACCENT);
        snprintf(line, sizeof(line), "KEY_NSPIRE_SCRATCHPAD (Save) : %s (Vu:%s)",
                 sp ? "APPUYE" : "non   ", last_sp ? "OUI" : "non");
        draw_text(14, 150, line, sp || last_sp ? COL_OK : COL_TEXT);
        snprintf(line, sizeof(line), "CTRL:%d  S:%d  DOC:%d  MENU:%d  ESC:%d",
                 ctrl ? 1 : 0, skey ? 1 : 0, doc ? 1 : 0, menu ? 1 : 0, esc ? 1 : 0);
        draw_text(14, 166, line, COL_TEXT);
        draw_text(14, 182, "Appuyez sur la touche entouree en rouge (Save).", COL_WARN);

        draw_box(8, 206, 304, 26, COL_CARD, COL_BORDER);
        draw_text(14, 215, "Maintenir [ESC] ou [ON] ~0.8s pour quitter.", COL_MUTED);

        lcd_blit(g_fb, SCR_320x240_565);
        safe_delay_ms(30);
    }

    lcd_init(SCR_TYPE_INVALID);
    free(g_fb);
    return 0;
}
